require_relative 'test_reporter'

GempyReporter.observe('  Strength (STR): 75 (12) ... 80 (15) ... 90 (20)')
GempyReporter.observe('  Logic (LOG): 100 (25) ... 100 (25)')
GempyReporter.observe(' Example (at level 100), your current skill bonuses and ranks (including all modifiers) are:')
GempyReporter.observe('  Arcane Symbols.....................| 302 202')
GempyReporter.observe('Spell Lists')
GempyReporter.observe('  Wizard.............................| 100')
GempyReporter.observe('Training Points: 0 Phy 0 Mnt')
GempyReporter.observe('Essence: 32,450/50,000 (Weekly)  118,750/200,000 (Total)')
data = GempyReporter.collect
assert(data.dig(:stats, :strength, :base_value) == 75, 'Full base stat')
assert(data.dig(:stats, :strength, :value) == 80, 'Current stat')
assert(data.dig(:stats, :logic, :base_value).nil?, 'Missing base stat stays unknown')
assert(data.dig(:skills, :arcane_symbols, :ranks) == 202, 'Skill ranks')
assert(data.dig(:skills, :wizard, :category) == 'spell_research', 'Spell research ranks')
assert(data.dig(:resources, :weekly) == 32450 && data.dig(:resources, :total) == 118750, 'Exact essence balances')
assert(data.dig(:resources, :type) == 'Essence', 'Resource name parsed from balances')
assert(data.dig(:resources, :max_weekly) == 50000, 'Cap comes from report')
observed = data.dig(:metadata, :availability, 'skills', :collected_at)
assert(observed == GempyReporter.collect.dig(:metadata, :availability, 'skills', :collected_at), 'Heartbeat does not refresh cached skill observation')
GempyReporter.observe('Your Gift of Lumnis will restart as soon as you absorb experience.')
assert(GempyReporter.collect.dig(:bonuses, :lumnis_points_remaining).nil?, 'Ready cycle clears old phase points')
GempyReporter.observe('You have made 2 recent donations to the Temple of Lumnis.')
assert(GempyReporter.collect.dig(:bonuses, :lumnis_donations) == 2, 'Prepaid donations')
GempyReporter.observe('Your Gift of Lumnis has expired for this week.')
assert(GempyReporter.collect.dig(:bonuses, :lumnis_stage) == 'expired', 'Cycle exhausted')
GempyReporter.observe(' Example (at level 100), your current skill bonuses and ranks (including all modifiers) are:')
GempyReporter.observe('  Arcane Symbols.....................| 5 1')
assert(GempyReporter.collect.dig(:skills, :arcane_symbols, :ranks) == 202, 'Partial skill reports do not replace complete data')
GempyReporter.observe('Training Points: 0 Phy 0 Mnt')
assert(!GempyReporter.collect[:skills].key?(:wizard), 'Completed retraining removes old spell ranks')
traffic = '<pushBold/>You have 1,234 points of quintupled experience remaining.<popBold/>'
assert(GempyReporter.observe(traffic) == traffic, 'XML traffic passes through unchanged')
assert(GempyReporter.collect.dig(:bonuses, :lumnis_stage) == 5, 'Phase-only line refreshes Lumnis')
GempyReporter.refresh_command('info full')
GempyReporter.refresh_command('skill')
GempyReporter.observe(%q{<dialogData id='expr'><progressBar fashlonae='2'/></dialogData>})
GempyReporter.observe("You are receiving Fash'lo'nae's Tutelage with 121 days remaining.")
fash=GempyReporter.collect[:bonuses]
assert(fash[:fashlonae_state]=='active', 'Duration report must not overwrite confirmed active multiplier')
assert(fash[:fashlonae_days_remaining]==121, 'Tutelage duration can exceed 90 days')
assert(fash[:fashlonae_observed_at].is_a?(Integer) && fash[:fashlonae_days_observed_at].is_a?(Integer), 'Independent state and duration timestamps')
GempyReporter.observe(%q{<dialogData id='expr'><progressBar id='mindState' fashlonae='1'/></dialogData>})
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='expended', 'Saga state 1 means expended for the week')
GempyReporter.observe("You are receiving Fash'lo'nae's Tutelage with 121 days remaining.")
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='expended', 'Duration does not reset weekly allowance')
assert(GempyReporter.collect[:bonuses][:fashlonae_days_remaining]==121, 'Expended benefit retains redeemed duration')
GempyReporter.observe('The feeling of heightened understanding departs.')
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='expended', 'Generic off message must not erase native weekly exhaustion')
GempyReporter.observe(%q{<dialogData id='expr'><progressBar id='mindState' tutelage='0'/></dialogData>})
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='inactive', 'Saga state 0 means available/inactive; attribute alias supported')
GempyReporter.observe('The feeling of heightened understanding departs.')
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='inactive', 'Off message confirms inactivity without guessing weekly allowance')
GempyReporter.observe("You are not presently receiving Fash'lo'nae's Tutelage.")
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='inactive', 'Text alone does not establish that benefit is unredeemed')
GempyReporter.observe(%q{<dialogData id='expr'><progressBar id='mindState' value='0'/></dialogData>})
assert(GempyReporter.collect[:bonuses][:fashlonae_state]=='unavailable', 'Absent attribute on complete mindState means unavailable')
assert(GempyReporter.collect[:bonuses][:fashlonae_days_remaining]==0, 'Unavailable clears old duration')
GempyReporter.observe('You feel a heightened understanding of events around you.')
assert(GempyReporter.collect[:bonuses][:fashlonae_days_remaining].nil?, 'New benefit must not inherit zero duration from not redeemed')
puts 'Profile stats, skills, essence and cycle transition checks passed'
